//! `benchmarks/LEADERBOARD.md` generation: one row per `(harness, model)`
//! pair, taken from the latest committed run (per ADR 086 §4).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::schema::{HarnessId, HostTier, ModelBacking, ModelTag, RunRecord};

/// Render the leaderboard markdown table from the already-selected
/// latest-per-pair map (see [`crate::store::latest_per_pair`]).
pub fn render_leaderboard_markdown(latest: &BTreeMap<(HarnessId, ModelTag), RunRecord>) -> String {
    let mut out = String::new();
    out.push_str("# Benchmark leaderboard\n\n");
    out.push_str(
        "Generated by `harness-core`'s `bench-tool leaderboard` from the latest committed run \
         per (harness, model) under `benchmarks/results/`. Do not hand-edit — regenerate instead.\n\n",
    );
    out.push_str(
        "Per ADR 086 §4: once a task-set hash has a published run against it, that hash is \
         frozen — task-set edits must land under a new hash (a \"v2\" series), not silently \
         change what a previously-published row measured.\n\n",
    );

    if latest.is_empty() {
        out.push_str("_No runs recorded yet under `benchmarks/results/`._\n");
        return out;
    }

    out.push_str(
        "| Harness | Model | Backing | Grading | Host tier | Date (UTC) | Tasks | Pass rate | Mean score | Task-set hash | Harness SHA |\n",
    );
    out.push_str("|---|---|---|---|---|---|---|---|---|---|---|\n");

    for ((harness, model_tag), record) in latest {
        let summary = record.summary();
        let backing = match &record.header.model.backing {
            ModelBacking::Cloud { provider_tag } => format!("cloud (`{provider_tag}`)"),
            ModelBacking::LocalGguf { file_name, file_hash } => {
                format!("local GGUF `{file_name}` (`{}`)", file_hash.short())
            }
        };
        let grading = match &record.header.grading {
            crate::schema::GradingMode::Autonomous => "autonomous".to_string(),
            crate::schema::GradingMode::Advisory(judge) => {
                format!("advisory (judge `{}`)", judge.judge_model)
            }
        };
        let host_tier = match &record.header.host_tier {
            HostTier::Host => "host".to_string(),
            HostTier::Vm(image) => format!("VM (`{}`)", image.registry),
        };

        let _ = writeln!(
            out,
            "| {harness} | {model_tag} | {backing} | {grading} | {host_tier} | {date} | {passed}/{total} | {pass_rate:.1}% | {mean_score:.3} | `{task_hash}` | `{sha}` |",
            date = record.header.timestamp.format("%Y-%m-%d"),
            passed = summary.passed,
            total = summary.total_tasks,
            pass_rate = summary.pass_rate * 100.0,
            mean_score = summary.mean_score,
            task_hash = record.header.task_set_hash.short(),
            sha = record.header.harness_git_sha.short(),
        );
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::schema::{
        Blake3Hex, GitSha, GradingMode, ModelIdentity, ResourceUsage, TaskId, TaskOutcome, TaskResult, TaskSetHash,
        WallTimeSecs,
    };

    fn record(harness: &str, model: &str) -> RunRecord {
        RunRecord::new(
            "2026-07-05T00:00:00Z".parse().unwrap(),
            HarnessId::new(harness).unwrap(),
            GitSha::new("774181cabcd0000000000000000000000000000").unwrap(),
            TaskSetHash::from_blake3(Blake3Hex::from_hash(blake3::hash(b"tasks"))),
            ModelIdentity {
                tag: ModelTag::new(model).unwrap(),
                backing: ModelBacking::Cloud {
                    provider_tag: format!("{model}-cloud"),
                },
            },
            GradingMode::Autonomous,
            HostTier::Host,
            vec![TaskResult::new(
                TaskId::new("t1").unwrap(),
                TaskOutcome::Pass,
                1.0,
                WallTimeSecs(1.0),
                ResourceUsage::none(),
                None,
            )
            .unwrap()],
        )
    }

    #[test]
    fn empty_leaderboard_says_so() {
        let md = render_leaderboard_markdown(&BTreeMap::new());
        assert!(md.contains("No runs recorded"));
    }

    #[test]
    fn leaderboard_contains_expected_rows() {
        let mut latest = BTreeMap::new();
        let r1 = record("demo", "deepseek");
        let r2 = record("demo", "glm");
        latest.insert(
            (HarnessId::new("demo").unwrap(), ModelTag::new("deepseek").unwrap()),
            r1,
        );
        latest.insert((HarnessId::new("demo").unwrap(), ModelTag::new("glm").unwrap()), r2);

        let md = render_leaderboard_markdown(&latest);
        assert!(md.contains("| demo | deepseek |"));
        assert!(md.contains("| demo | glm |"));
        assert!(md.contains("100.0%"));
    }
}
