#[cfg(test)]
mod tests {
    use super::*;
    use crate::agent::synthesize::NarrativeSection;
    use crate::pipeline::ReasoningResult;
    use std::path::PathBuf;

    fn sample_summary() -> NarrativeSummary {
        NarrativeSummary {
            overview: "The agent found 3 related entities.".into(),
            sections: vec![NarrativeSection {
                heading: "Entities".into(),
                prose: "Sun, Moon, Earth.".into(),
            }],
            gaps: vec!["orbital period missing".into()],
            facts_count: 3,
        }
    }

    #[test]
    fn new_formatter_is_not_available() {
        let f = CandleFormatter::new();
        assert!(!f.is_available());
    }

    #[test]
    fn try_load_nonexistent_returns_fallback_only() {
        let f = CandleFormatter::try_load(&PathBuf::from("/tmp/akh-nonexistent-candle-format-test"));
        assert!(!f.is_available());
    }

    #[test]
    fn format_narrative_fallback_contains_overview() {
        let f = CandleFormatter::new();
        let summary = sample_summary();
        let out = f.format(FormatInput::Narrative(&summary));
        assert_eq!(out.source, FormatSource::Fallback);
        assert!(out.text.contains("3 related entities"));
        assert!(out.text.contains("Sun, Moon, Earth"));
    }

    #[test]
    fn format_pipeline_fallback() {
        let f = CandleFormatter::new();
        let output = PipelineOutput {
            result: PipelineData::Reasoning(ReasoningResult {
                simplified_expr: "bundle 1 2".into(),
                cost: 5,
                saturated: true,
            }),
            stage_results: vec![],
            stages_executed: 2,
        };
        let out = f.format(FormatInput::Pipeline(&output));
        assert_eq!(out.source, FormatSource::Fallback);
        assert!(out.text.contains("2 stages"));
        assert!(out.text.contains("bundle 1 2"));
    }

    #[test]
    fn format_text_fallback_returns_input() {
        let f = CandleFormatter::new();
        let out = f.format(FormatInput::Text("hello world"));
        assert_eq!(out.source, FormatSource::Fallback);
        assert_eq!(out.text, "hello world");
    }

    #[test]
    fn latency_is_measured() {
        let f = CandleFormatter::new();
        let out = f.format(FormatInput::Text("timing test"));
        // latency_ms is always set (may be 0 on fast machines but is a u64)
        let _ = out.latency_ms;
    }

    #[test]
    fn try_format_without_backend_errors() {
        let f = CandleFormatter::new();
        let result = f.try_format(FormatInput::Text("test"));
        assert!(matches!(result, Err(CandleFormatError::BackendNotAvailable)));
    }

    #[test]
    fn describe_pipeline_data_variants() {
        use crate::infer::InferenceResult;
        use crate::symbol::SymbolId;

        let sym = SymbolId::new(1).unwrap();
        assert!(describe_pipeline_data(&PipelineData::Seeds(vec![sym])).contains('1'));
        assert!(describe_pipeline_data(&PipelineData::Triples(vec![])).contains('0'));
        assert!(describe_pipeline_data(&PipelineData::Inference(InferenceResult {
            activations: vec![(sym, 0.9)],
            pattern: None,
            provenance: vec![],
        }))
        .contains("activation"));
        assert!(describe_pipeline_data(&PipelineData::Reasoning(ReasoningResult {
            simplified_expr: "x".into(),
            cost: 1,
            saturated: false,
        }))
        .contains('x'));
    }

    #[test]
    fn build_narrative_prompt_contains_sections() {
        let summary = sample_summary();
        let prompt = build_narrative_prompt(&summary);
        assert!(prompt.contains("3 related entities"));
        assert!(prompt.contains("Entities"));
        assert!(prompt.contains("orbital period missing"));
        assert!(prompt.contains("<|im_start|>assistant"));
    }

    #[test]
    fn build_pipeline_prompt_contains_stages() {
        use crate::graph::traverse::TraversalResult;

        let output = PipelineOutput {
            result: PipelineData::Seeds(vec![]),
            stage_results: vec![(
                "retrieve".into(),
                PipelineData::Traversal(TraversalResult {
                    triples: vec![],
                    visited: Default::default(),
                    depth_reached: 0,
                }),
            )],
            stages_executed: 1,
        };
        let prompt = build_pipeline_prompt(&output);
        assert!(prompt.contains("retrieve"));
        assert!(prompt.contains("1 stages"));
    }

    #[test]
    fn fallback_pipeline_empty_data() {
        let output = PipelineOutput {
            result: PipelineData::Seeds(vec![]),
            stage_results: vec![],
            stages_executed: 0,
        };
        let text = fallback_format(&FormatInput::Pipeline(&output));
        assert!(text.contains("0 stages"));
    }
}
