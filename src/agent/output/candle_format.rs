//! Candle-based NL formatter for VSA structured agent output.
//!
//! Wraps [`CandleBackend`](crate::nlu::candle_backend::CandleBackend) to turn
//! VSA pipeline results and narrative summaries into fluent prose.
//!
//! ## Design contract
//! - Used ONLY for NL generation (structured → text).  Not for action selection,
//!   similarity search, or any VSA arithmetic — those remain pure VSA.
//! - Degrades gracefully: when the model file is absent or the `candle-backend`
//!   feature is disabled, `format()` returns a template-rendered fallback.
//! - Latency is always measured and returned so callers can benchmark the full
//!   VSA output → candle formatting → final text pipeline.

use std::path::Path;
use std::sync::{Arc, Mutex};
use std::time::Instant;

use miette::Diagnostic;
use thiserror::Error;

#[cfg(feature = "candle-backend")]
use crate::nlu::candle_backend::CandleBackend;

use crate::agent::synthesize::NarrativeSummary;
use crate::pipeline::{PipelineData, PipelineOutput};

// ---------------------------------------------------------------------------
// Error types
// ---------------------------------------------------------------------------

/// Errors from the Candle NL formatter.
#[derive(Debug, Error, Diagnostic)]
pub enum CandleFormatError {
    /// The Candle backend is not loaded (model absent or feature disabled).
    #[error("Candle NL formatter not available")]
    #[diagnostic(
        code(akh::agent::output::candle_not_available),
        help(
            "Place the GGUF model at <data_dir>/models/llm/qwen2.5-1.5b-instruct-q4_k_m.gguf \
             and the tokenizer at <data_dir>/models/llm/tokenizer.json, \
             or enable the `candle-backend` feature."
        )
    )]
    BackendNotAvailable,

    /// The LLM inference loop failed.
    #[error("Candle NL generation failed: {reason}")]
    #[diagnostic(
        code(akh::agent::output::generation_failed),
        help("Check tracing output for details. The formatter will fall back to template rendering.")
    )]
    GenerationFailed { reason: String },
}

/// Result type for Candle formatter operations.
pub type CandleFormatResult<T> = Result<T, CandleFormatError>;

// ---------------------------------------------------------------------------
// Input types
// ---------------------------------------------------------------------------

/// Structured VSA output to be rendered as natural language.
pub enum FormatInput<'a> {
    /// A complete narrative summary produced by `agent::synthesize`.
    Narrative(&'a NarrativeSummary),
    /// Raw pipeline output (inference, reasoning, traversal stages).
    Pipeline(&'a PipelineOutput),
    /// Freeform text to rephrase as fluent prose.
    Text(&'a str),
}

// ---------------------------------------------------------------------------
// Output types
// ---------------------------------------------------------------------------

/// Indicates which path produced the final text.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum FormatSource {
    /// Generated by the Candle LLM backend.
    Candle,
    /// Template rendering used (Candle was unavailable or returned empty).
    Fallback,
}

/// Result of a `CandleFormatter::format()` call.
#[derive(Debug, Clone)]
pub struct FormatOutput {
    /// The generated natural language text.
    pub text: String,
    /// How the text was generated.
    pub source: FormatSource,
    /// Wall-clock time from call entry to return, in milliseconds.
    pub latency_ms: u64,
}

// ---------------------------------------------------------------------------
// CandleFormatter
// ---------------------------------------------------------------------------

/// Formats VSA structured agent output as natural language.
///
/// Holds an optional shared [`CandleBackend`] (feature-gated).  When the
/// backend is absent, every call transparently falls back to rule-based
/// template rendering so the rest of the agent pipeline is unaffected.
pub struct CandleFormatter {
    #[cfg(feature = "candle-backend")]
    backend: Option<Arc<Mutex<CandleBackend>>>,
    /// Maximum tokens to generate per call (default: 256).
    pub max_tokens: u32,
}

impl std::fmt::Debug for CandleFormatter {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("CandleFormatter")
            .field("available", &self.is_available())
            .field("max_tokens", &self.max_tokens)
            .finish()
    }
}

impl Default for CandleFormatter {
    fn default() -> Self {
        Self::new()
    }
}

impl CandleFormatter {
    /// Create a formatter with no backend — every call uses fallback rendering.
    pub fn new() -> Self {
        Self {
            #[cfg(feature = "candle-backend")]
            backend: None,
            max_tokens: 256,
        }
    }

    /// Create a formatter backed by a pre-loaded, shared [`CandleBackend`].
    ///
    /// Passing the same `Arc` that the [`NluPipeline`] holds avoids loading
    /// the model twice.
    ///
    /// [`NluPipeline`]: crate::nlu::NluPipeline
    #[cfg(feature = "candle-backend")]
    pub fn from_backend(backend: Arc<Mutex<CandleBackend>>) -> Self {
        Self {
            backend: Some(backend),
            max_tokens: 256,
        }
    }

    /// Attempt to load a Candle backend from `data_dir`.
    ///
    /// Returns a formatter in fallback-only mode if the model files are absent
    /// or the `candle-backend` feature is disabled.
    pub fn try_load(data_dir: &Path) -> Self {
        #[cfg(feature = "candle-backend")]
        {
            if let Some(b) = CandleBackend::try_load(data_dir) {
                tracing::info!(
                    data_dir = %data_dir.display(),
                    "CandleFormatter: loaded model for NL generation"
                );
                return Self {
                    backend: Some(Arc::new(Mutex::new(b))),
                    max_tokens: 256,
                };
            }
            tracing::debug!(
                data_dir = %data_dir.display(),
                "CandleFormatter: model not found, using fallback rendering"
            );
        }
        #[cfg(not(feature = "candle-backend"))]
        {
            let _ = data_dir;
        }
        Self::new()
    }

    /// Returns `true` if the Candle backend is loaded and inference is possible.
    pub fn is_available(&self) -> bool {
        #[cfg(feature = "candle-backend")]
        {
            self.backend.is_some()
        }
        #[cfg(not(feature = "candle-backend"))]
        {
            false
        }
    }

    /// Format structured VSA output as natural language.
    ///
    /// Always succeeds: when Candle is unavailable or produces empty output,
    /// the call falls back to deterministic template rendering.
    ///
    /// # Latency benchmark
    ///
    /// `FormatOutput::latency_ms` covers the entire call: prompt construction,
    /// tokenisation, autoregressive decoding, and post-processing.  Log this
    /// value to track the VSA output → Candle formatting → final text pipeline.
    pub fn format<'a>(&self, input: FormatInput<'a>) -> FormatOutput {
        let start = Instant::now();
        let prompt = build_prompt(&input);

        #[cfg(feature = "candle-backend")]
        if let Some(ref backend_arc) = self.backend {
            match backend_arc.lock() {
                Ok(mut backend) => match backend.generate(&prompt, self.max_tokens) {
                    Ok(text) if !text.trim().is_empty() => {
                        let latency_ms = start.elapsed().as_millis() as u64;
                        tracing::debug!(
                            latency_ms,
                            approx_words = text.split_whitespace().count(),
                            "CandleFormatter: NL generation complete"
                        );
                        return FormatOutput {
                            text,
                            source: FormatSource::Candle,
                            latency_ms,
                        };
                    }
                    Ok(_) => {
                        tracing::debug!("CandleFormatter: empty output, using fallback");
                    }
                    Err(e) => {
                        tracing::warn!(
                            error = %e,
                            "CandleFormatter: generation failed, using fallback"
                        );
                    }
                },
                Err(e) => {
                    tracing::warn!(
                        error = %e,
                        "CandleFormatter: backend lock poisoned, using fallback"
                    );
                }
            }
        }

        let text = fallback_format(&input);
        let latency_ms = start.elapsed().as_millis() as u64;
        FormatOutput {
            text,
            source: FormatSource::Fallback,
            latency_ms,
        }
    }

    /// Attempt Candle generation and return an error if the backend is missing.
    ///
    /// Unlike `format()`, this variant does not fall back — callers that must
    /// know whether LLM generation succeeded should use this.
    pub fn try_format<'a>(&self, input: FormatInput<'a>) -> CandleFormatResult<FormatOutput> {
        if !self.is_available() {
            return Err(CandleFormatError::BackendNotAvailable);
        }
        let out = self.format(input);
        if out.source == FormatSource::Fallback {
            Err(CandleFormatError::GenerationFailed {
                reason: "backend returned empty output".into(),
            })
        } else {
            Ok(out)
        }
    }
}

// ---------------------------------------------------------------------------
// Prompt construction
// ---------------------------------------------------------------------------

fn build_prompt(input: &FormatInput<'_>) -> String {
    match input {
        FormatInput::Narrative(summary) => build_narrative_prompt(summary),
        FormatInput::Pipeline(output) => build_pipeline_prompt(output),
        FormatInput::Text(text) => build_text_prompt(text),
    }
}

fn build_narrative_prompt(summary: &NarrativeSummary) -> String {
    let mut body = summary.overview.clone();

    for section in &summary.sections {
        body.push_str("\n\n");
        body.push_str(&section.heading);
        body.push_str(": ");
        body.push_str(&section.prose);
    }

    if !summary.gaps.is_empty() {
        body.push_str("\n\nKnowledge gaps: ");
        body.push_str(&summary.gaps.join("; "));
    }

    format!(
        "<|im_start|>system\n\
         You are a concise assistant summarising knowledge graph findings in 2-4 sentences.\n\
         <|im_end|>\n\
         <|im_start|>user\n\
         {body}\n\n\
         Summarise these findings as a brief, readable response:\n\
         <|im_end|>\n\
         <|im_start|>assistant\n"
    )
}

fn build_pipeline_prompt(output: &PipelineOutput) -> String {
    let mut stages = String::new();
    for (stage_name, data) in &output.stage_results {
        stages.push_str(&format!(
            "  • {stage_name}: {}\n",
            describe_pipeline_data(data)
        ));
    }

    format!(
        "<|im_start|>system\n\
         You are a concise assistant presenting knowledge graph results clearly.\n\
         <|im_end|>\n\
         <|im_start|>user\n\
         Knowledge graph analysis ({} stages):\n{stages}\n\
         Present these findings in 1-3 sentences:\n\
         <|im_end|>\n\
         <|im_start|>assistant\n",
        output.stages_executed
    )
}

fn build_text_prompt(text: &str) -> String {
    format!(
        "<|im_start|>system\n\
         You are a concise assistant. Rephrase the following as clear, natural prose.\n\
         <|im_end|>\n\
         <|im_start|>user\n\
         {text}\n\
         <|im_end|>\n\
         <|im_start|>assistant\n"
    )
}

fn describe_pipeline_data(data: &PipelineData) -> String {
    match data {
        PipelineData::Seeds(seeds) => format!("{} seed symbols", seeds.len()),
        PipelineData::Triples(triples) => format!("{} triples", triples.len()),
        PipelineData::Traversal(tr) => format!(
            "{} nodes visited, {} triples",
            tr.visited.len(),
            tr.triples.len()
        ),
        PipelineData::Inference(ir) => format!(
            "{} activations (top score: {:.3})",
            ir.activations.len(),
            ir.activations.first().map(|(_, s)| *s).unwrap_or(0.0)
        ),
        PipelineData::Reasoning(rr) => format!(
            "simplified to '{}' (cost {})",
            rr.simplified_expr, rr.cost
        ),
    }
}

// ---------------------------------------------------------------------------
// Fallback template rendering
// ---------------------------------------------------------------------------

fn fallback_format(input: &FormatInput<'_>) -> String {
    match input {
        FormatInput::Narrative(summary) => {
            let mut out = summary.overview.clone();
            for section in &summary.sections {
                out.push(' ');
                out.push_str(&section.heading);
                out.push_str(": ");
                out.push_str(&section.prose);
            }
            out
        }
        FormatInput::Pipeline(output) => {
            let mut out = format!("Analysis completed {} stages.", output.stages_executed);
            if let Some(summary) = pipeline_data_summary(&output.result) {
                out.push(' ');
                out.push_str(&summary);
            }
            out
        }
        FormatInput::Text(text) => text.to_string(),
    }
}

fn pipeline_data_summary(data: &PipelineData) -> Option<String> {
    match data {
        PipelineData::Seeds(s) if !s.is_empty() => Some(format!("{} seed symbols.", s.len())),
        PipelineData::Triples(t) if !t.is_empty() => Some(format!("{} triples retrieved.", t.len())),
        PipelineData::Traversal(tr) if !tr.triples.is_empty() => Some(format!(
            "Traversed {} nodes ({} triples).",
            tr.visited.len(),
            tr.triples.len()
        )),
        PipelineData::Inference(ir) if !ir.activations.is_empty() => {
            Some(format!("{} activations inferred.", ir.activations.len()))
        }
        PipelineData::Reasoning(rr) if !rr.simplified_expr.is_empty() => {
            Some(format!("Reasoning result: {}.", rr.simplified_expr))
        }
        _ => None,
    }
}

