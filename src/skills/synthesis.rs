//! Dynamic skill synthesis: create skills from knowledge gaps.
//!
//! Phase 31e — when directed curiosity (Phase 11j) identifies a knowledge gap
//! that no existing skill covers, the synthesis pipeline:
//!   1. Ingests resources about the gap domain (web search, API).
//!   2. Consolidates the ingested triples.
//!   3. Uses Phase 30c's SkillAuthor to package the result as a new skill.
//!   4. Returns a `SkillCandidate` for user review before activation.
//!
//! This module provides the types and the orchestration stub; full execution
//! requires Phase 30c (LLM-assisted authoring) to be implemented.

use serde::{Deserialize, Serialize};

use crate::graph::Triple;

use super::discover::SkillCandidate;

/// A knowledge gap that motivated a synthesis attempt.
///
/// Typically produced by the directed curiosity module (Phase 11j).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SkillGap {
    /// Human-readable description of the gap.
    pub description: String,
    /// Domain tags associated with the gap.
    pub domain_tags: Vec<String>,
    /// Suggested skill name derived from the gap description.
    pub suggested_name: String,
    /// Concepts the agent tried to reason about but lacked knowledge for.
    pub missing_concepts: Vec<String>,
    /// Provenance token linking to the reasoning event that identified this gap.
    pub provenance_token: String,
}

/// Resources gathered to fill a knowledge gap (output of the ingestion step).
#[derive(Debug, Clone)]
pub struct IngestedResources {
    /// Triples extracted from the gathered resources.
    pub triples: Vec<Triple>,
    /// Source URLs or identifiers for the gathered content.
    pub sources: Vec<String>,
    /// Number of raw bytes ingested.
    pub bytes_ingested: usize,
}

/// Request to synthesize a skill.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SynthesisRequest {
    /// The knowledge gap that triggered this synthesis.
    pub gap: SkillGap,
    /// Maximum number of triples to include in the synthesized skill.
    pub max_triples: usize,
    /// Whether to require user approval before the candidate is promoted.
    pub require_approval: bool,
}

impl Default for SynthesisRequest {
    fn default() -> Self {
        Self {
            gap: SkillGap {
                description: String::new(),
                domain_tags: Vec::new(),
                suggested_name: String::new(),
                missing_concepts: Vec::new(),
                provenance_token: String::new(),
            },
            max_triples: 500,
            require_approval: true,
        }
    }
}

/// Outcome of a synthesis attempt.
#[derive(Debug, Clone)]
pub enum SynthesisResult {
    /// A candidate skill was produced and is pending user approval.
    Candidate(SkillCandidate),
    /// Synthesis was attempted but the gap was too narrow or resources were
    /// insufficient to build a coherent skill.
    InsufficientContent {
        gap_description: String,
        triples_found: usize,
        min_required: usize,
    },
    /// The gap is already covered by an existing skill (overlap detected).
    AlreadyCovered { covering_skill_id: String },
}

/// Build a `SkillCandidate` from already-ingested resources and a gap.
///
/// This is the core synthesis step after ingestion; the name and description
/// would normally be generated by an LLM (Phase 30c), but are populated from
/// the gap struct here so the pipeline can function without an LLM dependency.
pub fn synthesize_from_resources(
    request: &SynthesisRequest,
    resources: IngestedResources,
    min_triples: usize,
) -> SynthesisResult {
    if resources.triples.len() < min_triples {
        return SynthesisResult::InsufficientContent {
            gap_description: request.gap.description.clone(),
            triples_found: resources.triples.len(),
            min_required: min_triples,
        };
    }

    let core_triples = resources
        .triples
        .into_iter()
        .take(request.max_triples)
        .collect();

    let candidate = SkillCandidate {
        suggested_name: request.gap.suggested_name.clone(),
        suggested_description: request.gap.description.clone(),
        domain_tags: request.gap.domain_tags.clone(),
        core_triples,
        related_rules: Vec::new(),
        confidence: 0.6, // Moderate confidence for synthesized skills.
        provenance_token: request.gap.provenance_token.clone(),
    };

    SynthesisResult::Candidate(candidate)
}

/// Check if the gap is already covered by any skill whose prototype similarity
/// exceeds the given threshold.
///
/// `skill_similarities` maps skill IDs to their prototype similarity score
/// against the gap's domain vector (computed by the caller via Phase 31b).
pub fn check_gap_coverage(
    skill_similarities: &[(String, f32)],
    coverage_threshold: f32,
) -> Option<String> {
    skill_similarities
        .iter()
        .find(|(_, sim)| *sim > coverage_threshold)
        .map(|(id, _)| id.clone())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::graph::Triple;
    use crate::symbol::SymbolId;

    fn sym(n: u64) -> SymbolId {
        SymbolId::new(n).unwrap()
    }

    fn make_gap(name: &str) -> SkillGap {
        SkillGap {
            description: format!("Gap in {name} knowledge"),
            domain_tags: vec![name.to_string()],
            suggested_name: name.to_string(),
            missing_concepts: vec!["concept_a".to_string()],
            provenance_token: "prov-001".to_string(),
        }
    }

    fn make_triples(n: usize) -> Vec<Triple> {
        (0..n)
            .map(|i| Triple::new(sym(i as u64 + 1), sym(10), sym(i as u64 + 100)))
            .collect()
    }

    #[test]
    fn sufficient_content_produces_candidate() {
        let request = SynthesisRequest {
            gap: make_gap("robotics"),
            max_triples: 100,
            require_approval: true,
        };
        let resources = IngestedResources {
            triples: make_triples(20),
            sources: vec!["https://example.com".to_string()],
            bytes_ingested: 1024,
        };

        let result = synthesize_from_resources(&request, resources, 5);
        assert!(matches!(result, SynthesisResult::Candidate(_)));
        if let SynthesisResult::Candidate(c) = result {
            assert_eq!(c.suggested_name, "robotics");
            assert_eq!(c.core_triples.len(), 20);
        }
    }

    #[test]
    fn insufficient_content_returns_error() {
        let request = SynthesisRequest {
            gap: make_gap("exotic_domain"),
            ..Default::default()
        };
        let resources = IngestedResources {
            triples: make_triples(2),
            sources: Vec::new(),
            bytes_ingested: 100,
        };

        let result = synthesize_from_resources(&request, resources, 5);
        assert!(matches!(
            result,
            SynthesisResult::InsufficientContent {
                triples_found: 2,
                ..
            }
        ));
    }

    #[test]
    fn gap_coverage_detected() {
        let sims = vec![("math".to_string(), 0.45), ("physics".to_string(), 0.82)];
        let covering = check_gap_coverage(&sims, 0.75);
        assert_eq!(covering, Some("physics".to_string()));
    }

    #[test]
    fn gap_coverage_below_threshold() {
        let sims = vec![("math".to_string(), 0.45), ("physics".to_string(), 0.60)];
        let covering = check_gap_coverage(&sims, 0.75);
        assert!(covering.is_none());
    }

    #[test]
    fn max_triples_capped() {
        let request = SynthesisRequest {
            gap: make_gap("chemistry"),
            max_triples: 5,
            require_approval: true,
        };
        let resources = IngestedResources {
            triples: make_triples(100),
            sources: Vec::new(),
            bytes_ingested: 5000,
        };

        let result = synthesize_from_resources(&request, resources, 1);
        if let SynthesisResult::Candidate(c) = result {
            assert_eq!(c.core_triples.len(), 5);
        } else {
            panic!("expected Candidate");
        }
    }
}
