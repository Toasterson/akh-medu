class TorchEngine:
    """GPU engine over ``lilith_lora_trainer``: weighted SFT, sibling preference, adapter I/O.

    Checkpoint files written into the checkpoint directory: ``lora-state.pt`` (every LoRA tensor),
    ``optimizer.pt`` (AdamW state), ``rng.pt`` (torch CPU + CUDA RNG).
    """

    def __init__(self, model: Any, config: trainer.TrainerConfig, receipt: dict[str, Any], numerics: Any,
                 init_adapter: dict[str, Any] | None = None):
        import torch  # noqa: PLC0415
        self.torch = torch
        self.model, self.config, self.receipt, self.numerics = model, config, receipt, numerics
        self.optimizer = trainer.make_optimizer(model, config)
        self.init_adapter = init_adapter

    @classmethod
    def build(cls, context: EngineContext) -> 'TorchEngine':
        import torch  # noqa: PLC0415
        import lilith_numerics  # noqa: PLC0415
        if context.device.startswith('cuda') and (not torch.cuda.is_available() or torch.version.hip):
            raise ProgramError('lilith::program::cuda', 'requires the qualified NVIDIA CUDA path',
                               'run on the H100 pod; AMD/ROCm and CPU are unqualified for the 12B parent')
        numerics = lilith_numerics.cuda_default()
        torch.manual_seed(context.trainer_config.seed)
        random.seed(context.trainer_config.seed)
        model, receipt = trainer.load_training_model(context.parent, context.trainer_config, device=context.device)
        receipt['device'] = torch.cuda.get_device_name(0) if context.device.startswith('cuda') else context.device
        engine = cls(model, context.trainer_config, receipt, numerics, context.init_adapter)
        if context.init_adapter is not None:
            engine.load_init_adapter(Path(context.init_adapter['directory']), context.init_adapter.get('tensor_sha256'))
        return engine

    def load_init_adapter(self, directory: Path, expected_tensor_sha: str | None) -> None:
        from peft.utils import set_peft_model_state_dict  # noqa: PLC0415
        from safetensors.torch import load_file  # noqa: PLC0415
        result = set_peft_model_state_dict(self.model, load_file(str(directory / 'adapter_model.safetensors')))
        unexpected = list(getattr(result, 'unexpected_keys', []) or [])
        if unexpected:
            raise ProgramError('lilith::program::init_adapter_keys', f'{len(unexpected)} adapter tensors matched no module: {unexpected[:3]}',
                               'the starting adapter was trained on a different surface')
        observed = trainer.adapter_tensor_sha256(self.model)
        if expected_tensor_sha is not None and observed != expected_tensor_sha:
            raise ProgramError('lilith::program::init_adapter_tensors', 'loaded LoRA tensors differ from the adapter receipt',
                               'check dtype autocasting between PEFT versions; do not train from an unproven load')
        self.init_adapter = {**(self.init_adapter or {}), 'loaded_tensor_sha256': observed}

    def _set_lr(self, lr: float) -> None:
        for group in self.optimizer.param_groups:
            group['lr'] = lr

    def sft_step(self, examples: Sequence[trainer.SftExample], *, lr: float, step: int) -> StepOutcome:
        self._set_lr(lr)
        receipt = trainer.sft_step(self.model, self.optimizer, list(examples), self.config, step, numerics=self.numerics)
        return StepOutcome(receipt.loss, receipt.grad_norm, receipt.tokens, receipt.seconds, dict(receipt.extra))

    def preference_step(self, pairs: Sequence[trainer.PreferencePair], *, lr: float, step: int) -> StepOutcome:
        self._set_lr(lr)
        receipt = trainer.preference_step(self.model, self.optimizer, list(pairs), self.config, step, numerics=self.numerics)
        margins = receipt.extra.get('margins', [])
        return StepOutcome(receipt.loss, receipt.grad_norm, receipt.tokens, receipt.seconds,
                           {'margin_mean': sum(margins) / len(margins) if margins else 0.0, 'pairs': len(margins)})

    def dev_metrics(self, sft: Sequence[trainer.SftExample], pairs: Sequence[trainer.PreferencePair]) -> dict[str, Any]:
        torch = self.torch
        self.model.eval()
        nll, tokens, margins = 0.0, 0, []
        with torch.no_grad(), self.numerics.applied():
            for example in sft:
                logp = trainer.token_logps(self.model, example, self.config)
                mask = torch.tensor(example.target_mask[1:], dtype=logp.dtype, device=logp.device)
                nll += float(-(logp * mask).sum())
                tokens += int(sum(example.target_mask[1:]))
            for pair in pairs:
                chosen = float(trainer.sequence_logp(self.model, pair.chosen(), self.config))
                rejected = float(trainer.sequence_logp(self.model, pair.rejected(), self.config))
                with self.model.disable_adapter():
                    ref_chosen = float(trainer.sequence_logp(self.model, pair.chosen(), self.config))
                    ref_rejected = float(trainer.sequence_logp(self.model, pair.rejected(), self.config))
                margins.append((chosen - ref_chosen) - (rejected - ref_rejected))
        return {'sft_examples': len(sft), 'sft_supervised_tokens': tokens,
                'sft_nll_per_token': nll / tokens if tokens else None,
                'preference_pairs': len(pairs),
                'preference_margin_mean': sum(margins) / len(margins) if margins else None,
                'preference_margin_positive': sum(m > 0 for m in margins) / len(margins) if margins else None}

    def save_training_state(self, directory: Path) -> None:
        torch = self.torch
        lora = {name: tensor.detach().to('cpu').clone() for name, tensor in trainer.adapter_tensor_state(self.model).items()}
        torch.save(lora, directory / 'lora-state.pt')
        torch.save(self.optimizer.state_dict(), directory / 'optimizer.pt')
        torch.save({'torch': torch.get_rng_state(),
                    'cuda': torch.cuda.get_rng_state_all() if torch.cuda.is_available() else []}, directory / 'rng.pt')

    def load_training_state(self, directory: Path) -> None:
        torch = self.torch
        saved = torch.load(directory / 'lora-state.pt', map_location='cpu', weights_only=True)
        live = {trainer._strip_adapter_prefix(name): parameter for name, parameter in self.model.named_parameters()
                if '.lora_A.' in name or '.lora_B.' in name}
        if set(saved) != set(live):
            raise ProgramError('lilith::program::resume_surface', 'checkpoint LoRA tensors do not match the model surface',
                               'resume only with the same rank and trainer code that wrote the checkpoint')
        with torch.no_grad():
            for name, parameter in live.items():
                parameter.copy_(saved[name].to(device=parameter.device, dtype=parameter.dtype))
        self.optimizer.load_state_dict(torch.load(directory / 'optimizer.pt', map_location='cpu', weights_only=True))
        rng = torch.load(directory / 'rng.pt', map_location='cpu', weights_only=True)
        torch.set_rng_state(rng['torch'].cpu())
        if rng['cuda'] and torch.cuda.is_available() and len(rng['cuda']) == torch.cuda.device_count():
            torch.cuda.set_rng_state_all([state.cpu() for state in rng['cuda']])

    def save_adapter(self, directory: Path) -> dict[str, Any]:
        return trainer.save_adapter(self.model, directory, self.config).to_record()

    def write_cold_reload_probe(self, path: Path, adapter: dict[str, Any], input_ids: Sequence[int]) -> None:
        from reference_microrun import logits_record, probe_logits  # noqa: PLC0415
        with self.numerics.applied():
            probe = logits_record(probe_logits(self.model, list(input_ids)))
        write_json_atomic(path, {'adapter_dir': adapter['directory'], 'adapter': adapter,
                                 'probe': {'input_ids': list(input_ids), **probe}, 'trainer_config': self.config.to_record()})

    def describe(self) -> dict[str, Any]:
        return {'parent_pins': self.receipt.get('parent_pins'), 'surface': self.receipt.get('surface'),
                'trainer_config': self.config.to_record(), 'attention_implementation': self.receipt.get('attention_implementation'),
                'numerics': self.numerics.requested(), 'device': self.receipt.get('device'), 'init_adapter': self.init_adapter}

    def release_cache(self) -> None:
        import gc  # noqa: PLC0415
        gc.collect()
        if self.torch.cuda.is_available():
            self.torch.cuda.empty_cache()


