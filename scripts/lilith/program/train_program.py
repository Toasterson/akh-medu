def _require(condition: bool, code: str, message: str, help: str) -> None:
    if not condition:
        raise ProgramError(f'lilith::program::{code}', message, help)


def _is_int(value: Any) -> bool:
    return isinstance(value, int) and not isinstance(value, bool)


def parse_manifest(path: Path) -> ProgramManifest:
    """Read and structurally validate ``program-manifest.json``; hashing of archives is separate."""
    path = Path(path)
    _require(path.is_file(), 'manifest_missing', f'{path} is missing', 'pass the frozen program-manifest.json')
    raw_bytes = path.read_bytes()
    try:
        raw = json.loads(raw_bytes)
    except json.JSONDecodeError as error:
        raise ProgramError('lilith::program::manifest_json', f'{path} is not JSON: {error}',
                           'the manifest is produced by the corpus builder; rebuild it') from error
    _require(isinstance(raw, dict) and raw.get('schema') == MANIFEST_SCHEMA, 'manifest_schema',
             f'manifest schema {raw.get("schema") if isinstance(raw, dict) else None!r} is not {MANIFEST_SCHEMA}',
             'regenerate the manifest with the program corpus builder')
    run_id = raw.get('run_id')
    _require(isinstance(run_id, str) and _RUN_ID.match(run_id) is not None, 'manifest_run_id',
             f'run_id {run_id!r} is not a safe identifier', 'use letters, digits, dot, dash and underscore (3-80 chars)')
    parent = raw.get('parent') if isinstance(raw.get('parent'), dict) else raw
    revision = parent.get('revision', parent.get('parent_revision'))
    pins = parent.get('tokenizer_pins', parent.get('tokenizer'))
    _require(isinstance(revision, str) and isinstance(pins, dict), 'manifest_parent',
             'manifest lacks parent revision or tokenizer pins',
             'copy parent_revision and tokenizer_pins from corpus-v3/tokenization.json')
    _require(set(pins) == set(TOKENIZER_FILES) and all(isinstance(v, str) and _SHA256.match(v) for v in pins.values()),
             'manifest_pins', f'tokenizer pins must be exactly {TOKENIZER_FILES} with sha256 values',
             'an incomplete tokenizer/template pin set is refused')
    stages_raw = raw.get('stages')
    _require(isinstance(stages_raw, list) and stages_raw, 'manifest_stages', 'manifest has no stages', 'declare all five stages')
    stages = []
    declared_hashes = {}
    for key in ('files_sha256', 'archives_sha256'):
        if isinstance(raw.get(key), dict):
            declared_hashes.update(raw[key])
    for entry in stages_raw:
        _require(isinstance(entry, dict), 'manifest_stage', 'stage entry is not an object', 'see lilith/program-manifest@1')
        name = entry.get('name')
        archive = entry.get('archive')
        _require(name in STAGE_ORDER, 'manifest_stage', f'unknown stage {name!r}', f'stage names are {STAGE_ORDER}')
        _require(isinstance(archive, str) and archive and not Path(archive).is_absolute() and '..' not in Path(archive).parts,
                 'manifest_archive', f'stage {name} archive {archive!r} must be a relative path inside the data directory',
                 'archives are resolved next to the manifest')
        digest = entry.get('archive_sha256', declared_hashes.get(archive))
        _require(isinstance(digest, str) and _SHA256.match(digest) is not None, 'manifest_archive_sha',
                 f'stage {name} has no archive sha256', 'set stages[].archive_sha256 or files_sha256[<archive>]')
        order, sft_passes, pref_passes = entry.get('order'), entry.get('sft_passes'), entry.get('preference_passes')
        _require(_is_int(order) and _is_int(sft_passes) and _is_int(pref_passes) and sft_passes >= 0 and pref_passes >= 0
                 and sft_passes + pref_passes > 0, 'manifest_passes',
                 f'stage {name} needs integer order and non-negative sft_passes/preference_passes (not both zero)',
                 'freeze the per-stage passes in the manifest')
        lr = entry.get('lr_hint')
        _require(isinstance(lr, (int, float)) and not isinstance(lr, bool) and 0 < lr <= 1e-3, 'manifest_lr',
                 f'stage {name} lr_hint {lr!r} is outside (0, 1e-3]', 'LoRA rank-16 stages use about 1e-4')
        onpolicy = entry.get('onpolicy')
        spec = None
        if onpolicy is not None:
            _require(isinstance(onpolicy, dict) and isinstance(onpolicy.get('families'), list) and onpolicy['families']
                     and all(isinstance(f, str) for f in onpolicy['families']) and _is_int(onpolicy.get('quota'))
                     and onpolicy['quota'] > 0 and isinstance(onpolicy.get('snapshot_until'), str), 'manifest_onpolicy',
                     f'stage {name} onpolicy needs families, a positive quota and snapshot_until',
                     'see lilith/program-manifest@1; use null for no on-policy round')
            spec = OnPolicySpec(tuple(onpolicy['families']), onpolicy['quota'], onpolicy['snapshot_until'])
        counts = entry.get('counts') if isinstance(entry.get('counts'), dict) else {}
        stages.append(StageSpec(name, order, archive, digest, sft_passes, pref_passes, spec, float(lr), dict(counts)))
    stages.sort(key=lambda stage: stage.order)
    _require([s.name for s in stages] == list(STAGE_ORDER) and len({s.order for s in stages}) == len(stages),
             'manifest_stage_order', f'stages are {[s.name for s in stages]}; the program trains exactly {list(STAGE_ORDER)} in that order',
             'the canonical order is White, Yellow, Green, Brown, Black; never skip or reorder a stage')
    context = raw.get('context_limit')
    return ProgramManifest(run_id, revision, dict(pins), tuple(stages), sha256_bytes(raw_bytes), path.parent.resolve(),
                           context if _is_int(context) else None)


def verify_archives(manifest: ProgramManifest) -> dict[str, str]:
    """sha256 of every stage archive must equal the manifest pin."""
    observed = {}
    for stage in manifest.stages:
        path = manifest.directory / stage.archive
        _require(path.is_file(), 'archive_missing', f'{path} is missing', 'copy the archive next to the manifest')
        digest = sha256_file(path)
        _require(digest == stage.archive_sha256, 'archive_hash',
                 f'stage {stage.name} archive sha256 {digest} != manifest {stage.archive_sha256}',
                 'the archive drifted after the manifest was frozen; rebuild both, never edit one')
        observed[stage.name] = digest
    return observed


def verify_parent_pins(parent: Path, manifest: ProgramManifest) -> dict[str, str]:
    """Parent revision and the on-pod tokenizer/template files must match the manifest pins."""
    from lilith_adapter_mechanics import PARENT_REVISION  # noqa: PLC0415
    _require(manifest.parent_revision == PARENT_REVISION, 'parent_revision',
             f'manifest parent revision {manifest.parent_revision} != trainer pin {PARENT_REVISION}',
             'rebuild the corpus against the pinned parent revision')
    observed = {}
    for name, pin in manifest.tokenizer_pins.items():
        path = Path(parent) / name
        _require(path.is_file(), 'parent_file', f'{path} is missing', 'run scripts/lilith/runpod/bootstrap.sh')
        observed[name] = sha256_file(path)
        _require(observed[name] == pin, 'parent_pin', f'on-pod {name} differs from the prepared tokenization',
                 'the corpus was tokenized with another tokenizer/template; retokenize or restore the parent')
    return observed


