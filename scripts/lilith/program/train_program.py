#!/usr/bin/env python3
"""Lilith guided training program: White -> Yellow -> Green -> Brown -> Black from one frozen manifest.

Runs on the pod. One executable trains all five stages and resumes the same program across
resource windows (docs/ai/plans/2026-10-03-lilith-train-now-reconciliation.md, "Full training
scope" and "Execution order" 2-4; ADR 110 rule 7, ADR 116).

Per stage, in manifest order:

1. ``sft_passes`` passes of weighted SFT over the stage archive (``split == "train"``),
2. ``preference_passes`` passes of sibling-contrast preference over its pairs,
3. if the stage declares ``onpolicy``: save the stage adapter, write ``onpolicy-needed.json``
   and WAIT for the host's ``onpolicy-ready.json`` (an archive the host generated by serving
   that adapter and running the dojo), then one SFT pass + one preference pass over it.

Guards before any GPU work, each fail-closed: the manifest, every archive sha256, the parent pins
(revision + tokenizer/template files), the main-only payload, and an operator approval bound to the
manifest sha256 and the main SHA. ``--resume`` additionally refuses a different manifest, main SHA,
init adapter, seed or batch recipe. All state lives under ``<root>/program/<run_id>/`` and every
write is atomic; ``checkpoint.py`` documents the checkpoint protocol.

Exit codes: 0 all stages complete (``program-complete.json`` written); 75 the resource window
ended (checkpointed, resume me); 1 failure (diagnostic on stderr and in ``failure.json``).

The torch engine is deferred behind ``TrainEngine`` so the stage/cursor/checkpoint logic is
testable without a GPU. ``TorchEngine`` only composes the proven core in
``scripts/lilith/runpod/lilith_lora_trainer.py``; it adds no new loss arithmetic.
"""
