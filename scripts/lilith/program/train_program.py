class WindowEnd(Exception):
    """Raised inside the loop when the window must end cleanly (checkpoint already taken)."""

    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


class ProgramRunner:
    """Executes the unit list from the cursor; owns checkpoints, receipts and the on-policy handshake."""

    def __init__(self, *, args: ProgramArgs, manifest: ProgramManifest, stage_data: dict[str, StageData], run_dir: Path,
                 engine: TrainEngine, store: CheckpointStore, state: ProgramState, identity: dict[str, Any],
                 clock: Callable[[], float] = time.monotonic, sleep: Callable[[float], Any] = time.sleep,
                 stop_requested: Callable[[], bool] = lambda: False):
        self.args, self.manifest, self.stage_data, self.run_dir = args, manifest, stage_data, Path(run_dir)
        self.engine, self.store, self.state, self.identity = engine, store, state, identity
        self.clock, self.sleep, self.stop_requested = clock, sleep, stop_requested
        self.window_start = clock()
        self.base_elapsed = state.elapsed_seconds
        self.deadline = self.window_start + args.max_wall_seconds - args.early_stop_seconds
        self.dirty = False
        self._plans: dict[tuple[str, str, int], list[tuple[int, ...]]] = {}
        self._onpolicy_data: dict[str, StageData] = {}
        self.steps_path = self.run_dir / 'steps.jsonl'
        self.exit_reason = ''

    # ------------------------------------------------------------ planning

    def data_for(self, spec: StageSpec, phase: Phase) -> StageData:
        if phase in (Phase.ONPOLICY_SFT, Phase.ONPOLICY_PREFERENCE):
            if spec.name not in self._onpolicy_data:
                accepted = self.state.onpolicy.get(spec.name)
                if accepted is None:
                    raise ProgramError('lilith::program::onpolicy_state', f'stage {spec.name} has no accepted on-policy archive',
                                       'the handshake must complete before on-policy training')
                path = self.stage_dir(spec.name) / accepted['archive']
                if sha256_file(path) != accepted['sha256']:
                    raise ProgramError('lilith::program::onpolicy_hash', f'{path.name} changed since it was accepted',
                                       'never edit an accepted on-policy archive; restore it')
                self._onpolicy_data[spec.name] = load_archive(path, spec.name, self.manifest.context_limit)
            return self._onpolicy_data[spec.name]
        return self.stage_data[spec.name]

    def batches_for(self, spec: StageSpec, unit: Unit) -> list[tuple[int, ...]]:
        key = (spec.name, unit.phase.value, unit.pass_index)
        if key not in self._plans:
            data = self.data_for(spec, unit.phase)
            items = data.sft_train if unit.phase in (Phase.SFT, Phase.ONPOLICY_SFT) else data.pref_train
            seed = derive_seed(self.args.seed, spec.name, unit.phase.value, unit.pass_index)
            self._plans[key] = plan_batches([item.length for item in items], seed=seed, token_budget=self.args.token_budget,
                                            max_records=self.args.max_batch_records)
        return self._plans[key]

    def planned_main_steps(self, spec: StageSpec) -> dict[str, int]:
        out = {'sft': 0, 'preference': 0}
        for unit in units_for(spec):
            if unit.phase in (Phase.SFT, Phase.PREFERENCE):
                out[unit.phase.value] += len(self.batches_for(spec, unit))
        return out

    def stage_dir(self, stage: str) -> Path:
        path = self.run_dir / 'stages' / stage
        path.mkdir(parents=True, exist_ok=True)
        return path

    def segment(self, spec: StageSpec, phase: Phase) -> tuple[str, float, int, int]:
        """(segment name, peak lr, total steps, steps already done) for the LR schedule."""
        if phase in (Phase.ONPOLICY_SFT, Phase.ONPOLICY_PREFERENCE):
            total = sum(len(self.batches_for(spec, u)) for u in units_for(spec)
                        if u.phase in (Phase.ONPOLICY_SFT, Phase.ONPOLICY_PREFERENCE))
            done = self.state.steps_in(spec.name, 'onpolicy_sft') + self.state.steps_in(spec.name, 'onpolicy_preference')
            return 'onpolicy', spec.lr_hint * self.args.onpolicy_lr_scale, total, done
        planned = self.planned_main_steps(spec)
        done = self.state.steps_in(spec.name, 'sft') + self.state.steps_in(spec.name, 'preference')
        return 'main', spec.lr_hint, planned['sft'] + planned['preference'], done

    # --------------------------------------------------------- bookkeeping

    def elapsed(self) -> float:
        return self.base_elapsed + (self.clock() - self.window_start)

    def heartbeat(self, status: str, **extra: Any) -> None:
        spec = self.manifest.stages[min(self.state.cursor.stage_index, len(self.manifest.stages) - 1)]
        write_json_atomic(self.run_dir / 'progress.json', {
            'schema': 'lilith/program-progress@1', 'run_id': self.manifest.run_id, 'marker': self.args.marker, 'status': status,
            'stage': spec.name, 'stage_index': self.state.cursor.stage_index, 'phase': self.state.cursor.phase,
            'global_step': self.state.global_step, 'elapsed_seconds': round(self.elapsed(), 1), 'updated_at': utc_now(),
            'updated_epoch': time.time(), **extra})

    def write_budget(self) -> None:
        stages = {}
        for spec in self.manifest.stages:
            planned = self.planned_main_steps(spec)
            accepted = self.state.onpolicy.get(spec.name)
            onpolicy_planned = None
            if accepted is not None:
                onpolicy_planned = sum(len(self.batches_for(spec, u)) for u in units_for(spec)
                                       if u.phase in (Phase.ONPOLICY_SFT, Phase.ONPOLICY_PREFERENCE))
            stages[spec.name] = {
                'planned': {**planned, 'onpolicy': onpolicy_planned, 'onpolicy_declared': spec.onpolicy is not None},
                'done': dict(self.state.stage_steps.get(spec.name, {})),
                'data': self.stage_data[spec.name].summary()}
        planned_total = sum(s['planned']['sft'] + s['planned']['preference'] + (s['planned']['onpolicy'] or 0) for s in stages.values())
        write_json_atomic(self.run_dir / 'budget.json', {
            'schema': 'lilith/program-budget@1', 'run_id': self.manifest.run_id, 'stages': stages,
            'planned_steps_known': planned_total, 'done_steps': self.state.global_step, 'updated_at': utc_now()})

    def checkpoint(self, reason: str) -> None:
        if not self.dirty and self.state.checkpoint_seq > 0:
            return
        self.state.checkpoint_seq += 1
        self.state.elapsed_seconds = self.elapsed()
        version, internal, gauss = random.getstate()
        self.state.rng = {'python': [version, list(internal), gauss]}
        tmp = self.store.begin(self.state.checkpoint_seq)
        self.engine.save_training_state(tmp)
        self.store.commit(tmp, self.state)
        self.write_budget()
        self.dirty = False
        self.log_event('checkpoint', reason=reason, seq=self.state.checkpoint_seq, step=self.state.global_step)

    def log_event(self, event: str, **fields: Any) -> None:
        append_jsonl(self.run_dir / 'events.jsonl', {'event': event, 'at': utc_now(), 'step': self.state.global_step, **fields})

    def stop_reason(self) -> str | None:
        if self.stop_requested():
            return 'signal'
        if self.clock() >= self.deadline:
            return 'deadline'
        return None

    def end_window(self, reason: str) -> WindowEnd:
        self.checkpoint(f'window:{reason}')
        return WindowEnd(reason)

    # ------------------------------------------------------------- stepping

    def run_unit_batches(self, spec: StageSpec, unit: Unit) -> None:
        cursor = self.state.cursor
        batches = self.batches_for(spec, unit)
        data = self.data_for(spec, unit.phase)
        is_sft = unit.phase in (Phase.SFT, Phase.ONPOLICY_SFT)
        items = data.sft_train if is_sft else data.pref_train
        segment, peak, total, _ = self.segment(spec, unit.phase)
        for batch_index in range(cursor.batch_index, len(batches)):
            reason = self.stop_reason()
            if reason:
                raise self.end_window(reason)
            chosen = [items[i] for i in batches[batch_index]]
            _, _, _, done = self.segment(spec, unit.phase)
            lr = cosine_lr(peak, done, total)
            step = self.state.global_step
            if is_sft:
                outcome = self.engine.sft_step([item.example for item in chosen], lr=lr, step=step)
            else:
                outcome = self.engine.preference_step([item.pair for item in chosen], lr=lr, step=step)
            if not math.isfinite(outcome.loss) or not math.isfinite(outcome.grad_norm):
                raise ProgramError('lilith::program::nonfinite', f'step {step} produced a non-finite loss or gradient',
                                   'resume from the last checkpoint; inspect the batch ids in steps.jsonl')
            if step == 0 and outcome.grad_norm <= 0:
                raise ProgramError('lilith::program::zero_gradient', 'the first optimizer step had a zero gradient',
                                   'no supervised tokens reached the loss; check the target masks')
            weight_sum = sum(item.example.weight for item in chosen) if is_sft else sum(item.pair.weight for item in chosen)
            digest = sha256_bytes('\n'.join(item.record_id for item in chosen).encode())[:12]
            append_jsonl(self.steps_path, {
                'step': step, 'stage': spec.name, 'phase': unit.phase.value, 'pass': unit.pass_index, 'batch': batch_index,
                'records': len(chosen), 'batch_digest': digest, 'loss': outcome.loss, 'weight_sum': weight_sum,
                'tokens': outcome.tokens, 'lr': lr, 'grad_norm': outcome.grad_norm, 'seconds': outcome.seconds,
                'segment': segment, **{k: v for k, v in outcome.extra.items() if isinstance(v, (int, float, str))}})
            self.state.count_step(spec.name, unit.phase.value)
            self.state.scheduler = {'segment': segment, 'segment_step': done + 1, 'segment_total': total, 'last_lr': lr, 'peak_lr': peak}
            self.state.cursor = Cursor(self.state.cursor.stage_index, self.state.cursor.unit_index, batch_index + 1,
                                       unit.phase.value, unit.pass_index,
                                       derive_seed(self.args.seed, spec.name, unit.phase.value, unit.pass_index))
            self.dirty = True
            self.heartbeat('training', loss=outcome.loss, lr=lr)
            if self.state.global_step % self.args.checkpoint_steps == 0:
                self.checkpoint('periodic')

    # --------------------------------------------------------- stage adapters

    def ensure_adapter(self, directory: Path) -> dict[str, Any]:
        """Write-once adapter directory built under a temp name and renamed; idempotent on resume."""
        receipt_path = directory / 'lilith-adapter-receipt.json'
        if receipt_path.is_file():
            return read_json(receipt_path)
        tmp = directory.with_name(f'.{directory.name}.tmp')
        if tmp.exists():
            shutil.rmtree(tmp)
        if directory.exists():   # a directory without a receipt is a torn write
            shutil.rmtree(directory)
        record = self.engine.save_adapter(tmp)
        record['directory'] = str(directory)
        os.rename(tmp, directory)
        write_json_atomic(directory / 'lilith-adapter-receipt.json', record)
        ckpt.fsync_directory(directory.parent)
        return record

    @staticmethod
    def adapter_file_sha(record: dict[str, Any]) -> str:
        return record['files_sha256']['adapter_model.safetensors']

    # -------------------------------------------------------- on-policy handshake

    def request_onpolicy(self, spec: StageSpec) -> dict[str, Any]:
        stage_dir = self.stage_dir(spec.name)
        needed_path = stage_dir / 'onpolicy-needed.json'
        if needed_path.is_file():
            return read_json(needed_path)
        self.checkpoint('pre-onpolicy')       # the adapter below is exactly the checkpointed state
        adapter = self.ensure_adapter(stage_dir / 'adapter')
        assert spec.onpolicy is not None
        needed = {'schema': NEEDED_SCHEMA, 'run_id': self.manifest.run_id, 'stage': spec.name, 'families': list(spec.onpolicy.families),
                  'quota': spec.onpolicy.quota, 'snapshot_until': spec.onpolicy.snapshot_until,
                  'adapter_dir': str(stage_dir / 'adapter'), 'adapter_sha256': self.adapter_file_sha(adapter),
                  'adapter_tensor_sha256': adapter['tensor_sha256'], 'rank': adapter['rank'],
                  'archive_name': f'onpolicy-{spec.name}.tokens.jsonl', 'global_step': self.state.global_step,
                  'created_at': utc_now()}
        write_json_atomic(needed_path, needed)
        self.log_event('onpolicy_needed', stage=spec.name, adapter_sha256=needed['adapter_sha256'])
        return needed

    def try_accept_onpolicy(self, spec: StageSpec, needed: dict[str, Any]) -> bool:
        ready_path = self.stage_dir(spec.name) / 'onpolicy-ready.json'
        if not ready_path.is_file():
            return False
        ready = read_json(ready_path)
        expected_name = needed['archive_name']
        _require(isinstance(ready, dict) and ready.get('schema') == READY_SCHEMA and ready.get('stage') == spec.name
                 and ready.get('run_id', self.manifest.run_id) == self.manifest.run_id, 'onpolicy_ready',
                 f'{ready_path} is not a {READY_SCHEMA} for stage {spec.name}', 'the host writes it after rsyncing the archive')
        _require(ready.get('archive') == expected_name, 'onpolicy_archive_name',
                 f'ready names archive {ready.get("archive")!r}, expected {expected_name}', 'the archive is onpolicy-<stage>.tokens.jsonl')
        _require(ready.get('adapter_sha256') == needed['adapter_sha256'], 'onpolicy_adapter',
                 'the on-policy archive was generated by a different adapter than the one this run saved',
                 'regenerate the archive by serving stages/<stage>/adapter; a stale ready file must be removed by the host')
        archive = self.stage_dir(spec.name) / expected_name
        _require(archive.is_file() and isinstance(ready.get('sha256'), str), 'onpolicy_archive_missing',
                 f'{archive} is missing or ready has no sha256', 'rsync the archive before writing onpolicy-ready.json')
        digest = sha256_file(archive)
        _require(digest == ready['sha256'], 'onpolicy_archive_hash', f'{archive.name} sha256 {digest} != ready {ready["sha256"]}',
                 'the archive changed or was truncated in transfer; resend it')
        data = load_archive(archive, spec.name, self.manifest.context_limit)
        _require(data.sft_train or data.pref_train, 'onpolicy_empty', f'{archive.name} holds no trainable records',
                 'an empty on-policy round is a host failure; regenerate or remove the stage onpolicy block')
        self._onpolicy_data[spec.name] = data
        self.state.onpolicy[spec.name] = {'archive': expected_name, 'sha256': digest, 'adapter_sha256': needed['adapter_sha256'],
                                          'records': data.summary(), 'accepted_at': utc_now()}
        self.dirty = True
        self.log_event('onpolicy_accepted', stage=spec.name, sha256=digest)
        return True

    def wait_onpolicy(self, spec: StageSpec) -> None:
        needed = self.request_onpolicy(spec)
        if self.try_accept_onpolicy(spec, needed):
            return
        if self.args.onpolicy_wait_mode == 'exit':
            self.heartbeat('onpolicy_pending')
            raise self.end_window('onpolicy_pending')
        self.engine.release_cache()          # the host will start vLLM next to this process
        started = self.clock()
        while True:
            reason = self.wait_stop_reason(started)
            if reason:
                raise self.end_window(reason)
            self.heartbeat('waiting_onpolicy', waited_seconds=round(self.clock() - started, 1))
            if self.try_accept_onpolicy(spec, needed):
                return
            self.sleep(self.args.onpolicy_poll_seconds)

    def wait_stop_reason(self, started: float) -> str | None:
        """Signal, window deadline, then the per-wait ``--onpolicy-timeout``; any of them ends the window cleanly."""
        reason = self.stop_reason()
        if reason is None and self.clock() - started >= self.args.onpolicy_timeout:
            reason = 'onpolicy_timeout'
        return reason

    # ------------------------------------------------------------- stage loop

    def seal_stage(self, spec: StageSpec) -> None:
        """Dev loss (once), stage adapter(s) and stage-result.json; idempotent after a kill."""
        stage_dir = self.stage_dir(spec.name)
        if spec.name not in self.state.stage_results:
            data = self.stage_data[spec.name]
            sft_dev, pref_dev = pick_dev(data, self.args.dev_max)
            dev = self.engine.dev_metrics([i.example for i in sft_dev], [i.pair for i in pref_dev])
            self.state.stage_results[spec.name] = {'dev': dev, 'finished_at': utc_now()}
            self.dirty = True
            self.checkpoint(f'stage:{spec.name}')
        adapter_name = 'adapter-final' if spec.onpolicy is not None else 'adapter'
        adapter = self.ensure_adapter(stage_dir / adapter_name)
        result = {'schema': 'lilith/program-stage-result@1', 'run_id': self.manifest.run_id, 'stage': spec.name,
                  'steps': dict(self.state.stage_steps.get(spec.name, {})), 'dev': self.state.stage_results[spec.name]['dev'],
                  'adapter': adapter_name, 'adapter_sha256': self.adapter_file_sha(adapter),
                  'onpolicy': self.state.onpolicy.get(spec.name), 'finished_at': self.state.stage_results[spec.name]['finished_at']}
        write_json_atomic(stage_dir / 'stage-result.json', result)
        self.state.stage_results[spec.name]['adapter_sha256'] = result['adapter_sha256']
        self.log_event('stage_done', stage=spec.name, steps=result['steps'])

    def run(self) -> int:
        """Run from the cursor to completion; returns the process exit code."""
        self.log_event('window_start', window=self.state.windows, resumed_from_step=self.state.global_step)
        try:
            while self.state.cursor.stage_index < len(self.manifest.stages):
                index = self.state.cursor.stage_index
                spec = self.manifest.stages[index]
                units = units_for(spec)
                while self.state.cursor.unit_index < len(units):
                    unit = units[self.state.cursor.unit_index]
                    cursor = self.state.cursor
                    if cursor.phase != unit.phase.value or cursor.pass_index != unit.pass_index:
                        self.state.cursor = dataclasses.replace(cursor, phase=unit.phase.value, pass_index=unit.pass_index, batch_index=0)
                    if unit.phase is Phase.ONPOLICY_WAIT:
                        self.wait_onpolicy(spec)
                    else:
                        self.run_unit_batches(spec, unit)
                    self.state.cursor = Cursor(index, self.state.cursor.unit_index + 1, 0, unit.phase.value, unit.pass_index, 0)
                    self.dirty = True
                self.seal_stage(spec)
                self.state.cursor = Cursor(index + 1, 0, 0, Phase.SFT.value, 0, 0)
                self.dirty = True
            self.finalize()
            return EXIT_COMPLETE
        except WindowEnd as end:
            self.exit_reason = end.reason
            self.log_event('window_end', reason=end.reason)
            return EXIT_WINDOW

    # -------------------------------------------------------------- finalize

    def finalize(self) -> None:
        self.checkpoint('all-stages')        # a failure below resumes straight here, with the final weights
        candidate_dir = self.run_dir / 'candidate-adapter'
        adapter = self.ensure_adapter(candidate_dir)
        probe_ids = self.first_probe_ids()
        probe_state = 'skipped: no train record'
        if probe_ids:
            try:
                self.engine.write_cold_reload_probe(self.run_dir / 'cold-reload.probe.json', adapter, probe_ids)
                probe_state = 'written'
            except Exception as error:   # the probe is a convenience for the reload check, never the artifact
                probe_state = f'failed: {type(error).__name__}: {error}'
        provenance = self.identity.get('payload', {})
        manifest_record = {
            'schema': CANDIDATE_SCHEMA, 'run_id': self.manifest.run_id, 'status': 'candidate_inactive', 'activated': False,
            'quality_claim': False, 'release_selected': False, 'reward_policy': REWARD_POLICY,
            'adapter': {**adapter, 'adapter_model_sha256': self.adapter_file_sha(adapter)},
            'parent': {'repo': trainer.PARENT_REPO, 'revision': self.manifest.parent_revision,
                       'tokenizer_pins': self.manifest.tokenizer_pins, **self.engine.describe()},
            'program_manifest_sha256': self.manifest.sha256, 'archives_sha256': {s.name: s.archive_sha256 for s in self.manifest.stages},
            'code': {'main_sha': self.identity['main_sha'], 'payload_manifest_sha256': provenance.get('manifest_sha256')},
            'approval_sha256': self.identity.get('approval_sha256'), 'init_adapter': self.identity.get('init_adapter'),
            'seed': self.args.seed, 'stage_steps': self.state.stage_steps, 'total_steps': self.state.global_step,
            'onpolicy': self.state.onpolicy, 'windows': self.state.windows, 'cold_reload_probe': probe_state,
            'created_at': utc_now()}
        write_json_atomic(self.run_dir / 'candidate-manifest.json', manifest_record)
        complete = {
            'schema': COMPLETE_SCHEMA, 'run_id': self.manifest.run_id, 'completed_at': utc_now(), 'total_steps': self.state.global_step,
            'elapsed_seconds': round(self.elapsed(), 1), 'windows': self.state.windows,
            'stages': {s.name: {'steps': self.state.stage_steps.get(s.name, {}), 'dev': self.state.stage_results[s.name]['dev']}
                       for s in self.manifest.stages},
            'final_adapter_sha256': manifest_record['adapter']['adapter_model_sha256'],
            'final_adapter_tensor_sha256': adapter['tensor_sha256'],
            'candidate_manifest_sha256': sha256_file(self.run_dir / 'candidate-manifest.json')}
        write_json_atomic(self.run_dir / 'program-complete.json', complete)   # written last
        self.heartbeat('complete')

    def first_probe_ids(self) -> list[int]:
        for spec in self.manifest.stages:
            items = self.stage_data[spec.name].sft_train
            if items:
                return list(items[0].example.input_ids[:16])
        return []


# ------------------------------------------------------------------------ driver

def _identity_record(args: ProgramArgs, manifest: ProgramManifest, approval: Approval, init: dict[str, Any] | None,
                     provenance: dict[str, Any], config: trainer.TrainerConfig) -> dict[str, Any]:
    return {'schema': IDENTITY_SCHEMA, 'run_id': manifest.run_id, 'manifest_sha256': manifest.sha256, 'main_sha': args.main_sha,
            'approval_sha256': approval.file_sha256, 'init_adapter': init, 'seed': args.seed, 'token_budget': args.token_budget,
            'max_batch_records': args.max_batch_records, 'onpolicy_lr_scale': args.onpolicy_lr_scale,
            'trainer_config': config.to_record(), 'payload': {'manifest_sha256': provenance.get('manifest_sha256')},
            'created_at': utc_now()}


RESUME_BINDS = ('run_id', 'manifest_sha256', 'main_sha', 'seed', 'token_budget', 'max_batch_records', 'onpolicy_lr_scale')


def check_resume_identity(existing: dict[str, Any], fresh: dict[str, Any]) -> None:
    """A resume continues the same program: manifest, main SHA, init adapter and batch recipe must be identical."""
    for key in RESUME_BINDS:
        if existing.get(key) != fresh.get(key):
            raise ProgramError('lilith::program::resume_identity', f'{key} differs from the run being resumed '
                               f'({existing.get(key)!r} != {fresh.get(key)!r})',
                               'resume refuses a different manifest, main SHA or recipe; start a new run_id instead')
    old_init = (existing.get('init_adapter') or {}).get('adapter_model_sha256')
    new_init = (fresh.get('init_adapter') or {}).get('adapter_model_sha256')
    if old_init != new_init:
        raise ProgramError('lilith::program::resume_identity', f'init adapter differs ({old_init!r} != {new_init!r})',
                           'a resume must name the same starting adapter')
    if existing.get('trainer_config', {}).get('rank') != fresh['trainer_config']['rank']:
        raise ProgramError('lilith::program::resume_identity', 'LoRA rank differs', 'resume with the rank that wrote the checkpoint')


PayloadVerifier = Callable[[Path, str], dict[str, Any]]


def default_payload_verifier(payload_root: Path, main_sha: str) -> dict[str, Any]:
    return verify_payload.verify(payload_root, payload_root / 'source-manifest.json', main_sha, False)


def _decode_python_rng(record: dict[str, Any]) -> Any:
    version, internal, gauss = record['python']
    return version, tuple(internal), gauss


def run_program(args: ProgramArgs, *, engine_factory: EngineFactory = TorchEngine.build,
                payload_verifier: PayloadVerifier = default_payload_verifier,
                clock: Callable[[], float] = time.monotonic, sleep: Callable[[float], Any] = time.sleep,
                stop_requested: Callable[[], bool] = lambda: False) -> int:
    """Verify, build or resume, run to the end of the window or the program; returns the exit code."""
    manifest = parse_manifest(args.manifest)
    root = Path(args.root)
    if not str(root.resolve()).startswith('/workspace/') and os.environ.get('LILITH_ALLOW_NON_WORKSPACE') != '1':
        raise ProgramError('lilith::program::root', f'root {root} is not on the /workspace volume',
                           'a pod stop wipes everything else; set --root under /workspace')
    run_dir = root / 'program' / manifest.run_id
    complete_path = run_dir / 'program-complete.json'
    config = trainer.TrainerConfig(rank=args.rank, learning_rate=1e-4, seed=args.seed)
    archive_hashes = verify_archives(manifest)
    verify_parent_pins(args.parent, manifest)
    payload_root = args.payload_root or HERE.parents[3]
    provenance = payload_verifier(payload_root, args.main_sha)
    _require(provenance.get('status') == 'verified', 'payload',
             'main-only source payload verification failed: ' + '; '.join(provenance.get('problems', [])),
             'rebuild the payload with scripts/lilith/runpod/make_payload.sh from a clean origin/main commit')
    init_sha = args.init_adapter_sha256
    _require((args.init_adapter is None) == (init_sha is None), 'init_adapter_pin',
             '--init-adapter and its sha256 go together', 'pass both or neither')
    approval = load_approval(args.approval, manifest, args.main_sha, init_sha)
    init = check_init_adapter(args.init_adapter, init_sha, config) if args.init_adapter is not None and init_sha else None
    stage_data: dict[str, StageData] = {}
    for spec in manifest.stages:
        stage_data[spec.name] = load_archive(manifest.directory / spec.archive, spec.name, manifest.context_limit)
        verify_counts(spec, stage_data[spec.name])
        _require(stage_data[spec.name].sft_train or stage_data[spec.name].pref_train, 'stage_empty',
                 f'stage {spec.name} has no trainable record', 'an empty stage is not a stage; fix the corpus')

    identity_path = run_dir / 'identity.json'
    identity = _identity_record(args, manifest, approval, init, provenance, config)
    if args.resume:
        _require(identity_path.is_file(), 'resume_nothing', f'{identity_path} does not exist', 'start the program without --resume')
        existing = read_json(identity_path)
        check_resume_identity(existing, identity)
        identity = {**existing, 'approval_sha256': approval.file_sha256}
    else:
        _require(not identity_path.exists(), 'run_exists', f'{run_dir} already has an identity',
                 'refusing to overwrite a run; use --resume to continue it, or a new run_id')
    if complete_path.is_file():
        print(json.dumps({'run_id': manifest.run_id, 'status': 'complete', 'program_complete': str(complete_path)}))
        return EXIT_COMPLETE
    run_dir.mkdir(parents=True, exist_ok=True)
    run_dir.chmod(0o700)
    if not args.resume:
        write_json_atomic(identity_path, identity)

    store = CheckpointStore(run_dir)
    store.clean_stale()
    found = store.newest_valid() if args.resume else None
    state = found[1] if found else ProgramState()
    engine = engine_factory(EngineContext(args.parent, config, init))
    if found:
        engine.load_training_state(found[0])
        random.setstate(_decode_python_rng(state.rng))
        truncate_jsonl(run_dir / 'steps.jsonl', lambda record: record['step'] < state.global_step)
        ckpt_note = f'resumed from {found[0].name} at step {state.global_step}'
    else:
        truncate_jsonl(run_dir / 'steps.jsonl', lambda record: False)
        ckpt_note = 'no checkpoint: starting at the first stage' if args.resume else 'fresh start'
    state.windows += 1
    ckpt.append_jsonl(run_dir / 'windows.jsonl', {'event': 'start', 'window': state.windows, 'marker': args.marker, 'at': utc_now(),
                                                  'note': ckpt_note, 'approval_sha256': approval.file_sha256,
                                                  'max_wall_seconds': args.max_wall_seconds, 'archives': archive_hashes})
    runner = ProgramRunner(args=args, manifest=manifest, stage_data=stage_data, run_dir=run_dir, engine=engine, store=store,
                           state=state, identity=identity, clock=clock, sleep=sleep, stop_requested=stop_requested)
    runner.dirty = True
    runner.write_budget()
    code = runner.run()
    ckpt.append_jsonl(run_dir / 'windows.jsonl', {'event': 'end', 'window': state.windows, 'marker': args.marker, 'at': utc_now(),
                                                  'exit_code': code, 'reason': runner.exit_reason or 'complete',
                                                  'global_step': state.global_step, 'elapsed_seconds': round(runner.elapsed(), 1)})
    write_json_atomic(run_dir / 'window-exit.json', {'schema': 'lilith/program-window-exit@1', 'marker': args.marker, 'exit_code': code,
                                                     'reason': runner.exit_reason or 'complete', 'global_step': state.global_step,
                                                     'at': utc_now()})
    return code


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    stop = threading.Event()
    for signum in (signal.SIGTERM, signal.SIGINT):
        signal.signal(signum, lambda *_: stop.set())     # checkpoint at the next step boundary, exit 75
    os.umask(0o077)
    try:
        return run_program(args, sleep=lambda seconds: stop.wait(seconds), stop_requested=stop.is_set)
    except ProgramError as error:
        print(f'train_program: error{error}', file=sys.stderr)
        failure = {'schema': 'lilith/program-failure@1', 'code': error.code, 'message': str(error), 'help': error.help,
                   'marker': args.marker, 'at': utc_now()}
    except BaseException as error:   # noqa: BLE001 - every failure leaves a diagnostic for the supervisor
        print(f'train_program: error: {type(error).__name__}: {error}', file=sys.stderr)
        failure = {'schema': 'lilith/program-failure@1', 'code': 'lilith::program::unexpected',
                   'message': f'{type(error).__name__}: {error}', 'help': 'inspect the log; resume from the last checkpoint',
                   'marker': args.marker, 'at': utc_now()}
    try:
        run_dir = Path(args.root) / 'program' / parse_manifest(args.manifest).run_id
        if run_dir.is_dir():
            write_json_atomic(run_dir / 'failure.json', failure)
            write_json_atomic(run_dir / 'window-exit.json', {'schema': 'lilith/program-window-exit@1', 'marker': args.marker,
                                                             'exit_code': EXIT_FAILURE, 'reason': failure['code'], 'at': utc_now()})
    except Exception:   # noqa: BLE001 - the stderr line above is the fallback record
        pass
    return EXIT_FAILURE


if __name__ == '__main__':
    raise SystemExit(main())
