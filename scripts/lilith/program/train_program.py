def _seq_ok(ids: Any, mask: Any, where: str) -> None:
    _require(isinstance(ids, list) and isinstance(mask, list) and len(ids) == len(mask) and len(ids) >= 2, 'record_shape',
             f'{where}: input_ids/target_mask missing, unequal or too short', 'records need input_ids and target_mask of equal length')
    _require(all(_is_int(i) and 0 <= i < VOCAB_SIZE for i in ids), 'record_ids', f'{where}: token id outside the vocabulary',
             'retokenize with the pinned Gemma tokenizer')
    _require(all(type(m) is bool for m in mask) and not mask[0] and any(mask), 'record_mask',
             f'{where}: target_mask must be booleans, mask the first token and supervise at least one token',
             'drop examples without assistant tokens')


def _suffix_mask(mask: Sequence[bool]) -> int | None:
    """Index where a prompt-then-answer mask turns True, or None if the mask is not of that shape."""
    boundary = mask.index(True)
    return boundary if all(mask[boundary:]) else None


def _build_sft(record: dict[str, Any], where: str, context_limit: int | None) -> SftItem:
    ids, mask, weight = record.get('input_ids'), record.get('target_mask'), record['weight']
    _seq_ok(ids, mask, where)
    _require(context_limit is None or len(ids) <= context_limit, 'record_context',
             f'{where}: {len(ids)} tokens exceed the {context_limit}-token context', 'oversized records are reported, never truncated')
    boundary = _suffix_mask(mask)
    if boundary is not None:   # prompt + answer: the core's own builder
        example = trainer.build_sft_example(ids[:boundary], ids[boundary:], weight=weight, source=record['record_id'])
    else:                      # multi-turn with masked observations between supervised spans
        example = trainer.SftExample(tuple(ids), tuple(mask), float(weight), record['record_id'])
    return SftItem(record['record_id'], example, len(ids))


def _build_preference(record: dict[str, Any], where: str, context_limit: int | None) -> PreferenceItem:
    chosen, rejected = record.get('chosen'), record.get('rejected')
    _require(isinstance(chosen, dict) and isinstance(rejected, dict), 'pair_shape', f'{where}: preference needs chosen and rejected',
             'see lilith/program-tokens@1')
    for side, name in ((chosen, 'chosen'), (rejected, 'rejected')):
        _seq_ok(side.get('input_ids'), side.get('target_mask'), f'{where} {name}')
        _require(context_limit is None or len(side['input_ids']) <= context_limit, 'record_context',
                 f'{where} {name}: exceeds the {context_limit}-token context', 'oversized records are reported, never truncated')
    boundary_c, boundary_r = _suffix_mask(chosen['target_mask']), _suffix_mask(rejected['target_mask'])
    _require(boundary_c is not None and boundary_c == boundary_r and chosen['input_ids'][:boundary_c] == rejected['input_ids'][:boundary_r],
             'pair_prefix', f'{where}: chosen and rejected must share one prompt prefix and supervise only the response after it',
             'preference pairs are prompt + one response each; express multi-turn corrections as SFT records')
    try:
        pair = trainer.PreferencePair(tuple(chosen['input_ids'][:boundary_c]), tuple(chosen['input_ids'][boundary_c:]),
                                      tuple(rejected['input_ids'][boundary_r:]), float(record['weight']), record['record_id'])
    except trainer.LilithTrainerError as error:
        raise ProgramError('lilith::program::pair_invalid', f'{where}: {error}', 'drop pairs without contrast') from error
    return PreferenceItem(record['record_id'], pair, len(chosen['input_ids']) + len(rejected['input_ids']))


def load_archive(path: Path, stage: str, context_limit: int | None = None) -> StageData:
    """Parse a ``lilith/program-tokens@1`` archive into typed examples (train and dev; zero weight dropped)."""
    data = StageData(stage)
    seen: set[str] = set()
    for number, line in enumerate(Path(path).read_text().splitlines(), 1):
        if not line.strip():
            continue
        where = f'{Path(path).name}:{number}'
        try:
            record = json.loads(line)
        except json.JSONDecodeError as error:
            raise ProgramError('lilith::program::record_json', f'{where}: not JSON ({error})', 'rebuild the archive') from error
        if isinstance(record, dict) and 'record_id' not in record and record.get('schema') == TOKENS_SCHEMA:
            continue                                   # optional header line
        _require(isinstance(record, dict) and isinstance(record.get('record_id'), str) and record['record_id'],
                 'record_id', f'{where}: record_id missing', 'every record carries a unique record_id')
        _require(record.get('schema', TOKENS_SCHEMA) == TOKENS_SCHEMA, 'record_schema', f'{where}: schema is not {TOKENS_SCHEMA}', 'rebuild')
        _require(record['record_id'] not in seen, 'record_duplicate', f'{where}: duplicate record_id {record["record_id"]}', 'deduplicate')
        seen.add(record['record_id'])
        _require(record.get('stage') == stage, 'record_stage', f'{where}: record stage {record.get("stage")!r} != archive stage {stage}',
                 'an archive holds one stage')
        kind, split, weight = record.get('kind'), record.get('split'), record.get('weight')
        _require(kind in ('sft', 'preference'), 'record_kind', f'{where}: kind {kind!r}', 'kinds are sft and preference')
        _require(isinstance(weight, (int, float)) and not isinstance(weight, bool) and math.isfinite(weight) and 0.0 <= weight <= 1.0,
                 'record_weight', f'{where}: weight {weight!r} outside [0, 1]', 'ADR 110 rule 7: weights are never a penalty')
        data.totals[f'{kind}_{split}'] = data.totals.get(f'{kind}_{split}', 0) + 1
        if split not in ('train', 'dev'):
            data.skipped['other_split'] = data.skipped.get('other_split', 0) + 1
            continue
        if weight == 0:    # silence, not punishment: it teaches nothing, so it costs no step
            data.skipped['zero_weight'] = data.skipped.get('zero_weight', 0) + 1
            continue
        if kind == 'sft':
            item = _build_sft(record, where, context_limit)
            (data.sft_train if split == 'train' else data.sft_dev).append(item)
        else:
            item = _build_preference(record, where, context_limit)
            (data.pref_train if split == 'train' else data.pref_dev).append(item)
    return data


def verify_counts(spec: StageSpec, data: StageData) -> None:
    """Declared ``counts`` (keys sft, preference = records of that kind; train, dev = records in that split)."""
    observed = {'sft': sum(v for k, v in data.totals.items() if k.startswith('sft_')),
                'preference': sum(v for k, v in data.totals.items() if k.startswith('preference_')),
                'train': sum(v for k, v in data.totals.items() if k.endswith('_train')),
                'dev': sum(v for k, v in data.totals.items() if k.endswith('_dev'))}
    for key, declared in spec.counts.items():
        if key in observed:
            _require(declared == observed[key], 'counts', f'stage {spec.name} declares {key}={declared} but the archive has {observed[key]}',
                     'the manifest counts and the archive disagree; rebuild both')


def pick_dev(data: StageData, limit: int) -> tuple[list[SftItem], list[PreferenceItem]]:
    """A small deterministic dev slice: first ``limit`` records by sha256(record_id)."""
    key = lambda item: sha256_bytes(item.record_id.encode())   # noqa: E731
    return sorted(data.sft_dev, key=key)[:limit], sorted(data.pref_dev, key=key)[:limit]


# ----------------------------------------------------------------- batching and LR

def derive_seed(base: int, *parts: object) -> int:
    return int.from_bytes(hashlib.sha256('|'.join([str(base), *map(str, parts)]).encode()).digest()[:8], 'big')


def plan_batches(lengths: Sequence[int], *, seed: int, token_budget: int, max_records: int,
                 bucket_size: int = 64) -> list[tuple[int, ...]]:
    """Seeded shuffle, then length-bucketed greedy packing within a token budget.

    Deterministic in (lengths, seed, budget): a resumed run recomputes exactly the same batches.
    A record longer than the budget gets a batch of its own. Batch order is shuffled again.
    """
    _require(token_budget > 0 and max_records > 0 and bucket_size > 0, 'batch_plan', 'token budget, record cap and bucket must be positive',
             'defaults are 16384 / 64 / 64')
    rng = random.Random(seed)
    order = list(range(len(lengths)))
    rng.shuffle(order)
    batches: list[tuple[int, ...]] = []
    for start in range(0, len(order), bucket_size):
        bucket = sorted(order[start:start + bucket_size], key=lambda i: (lengths[i], i))
        current: list[int] = []
        used = 0
        for index in bucket:
            if current and (used + lengths[index] > token_budget or len(current) >= max_records):
                batches.append(tuple(current))
                current, used = [], 0
            current.append(index)
            used += lengths[index]
        if current:
            batches.append(tuple(current))
    rng.shuffle(batches)
    return batches


def cosine_lr(peak: float, step: int, total: int) -> float:
    """Linear warmup over the first 5% (at least one step), then cosine down to 10% of peak."""
    if total <= 1:
        return peak
    warmup = max(1, math.ceil(LR_WARMUP_FRACTION * total))
    if step < warmup:
        return peak * (step + 1) / warmup
    progress = min(1.0, (step - warmup) / max(1, total - warmup))
    floor = peak * LR_FLOOR_FRACTION
    return floor + (peak - floor) * 0.5 * (1.0 + math.cos(math.pi * progress))


def units_for(spec: StageSpec) -> list[Unit]:
    units = [Unit(Phase.SFT, p) for p in range(spec.sft_passes)] + [Unit(Phase.PREFERENCE, p) for p in range(spec.preference_passes)]
    if spec.onpolicy is not None:
        units += [Unit(Phase.ONPOLICY_WAIT), Unit(Phase.ONPOLICY_SFT), Unit(Phase.ONPOLICY_PREFERENCE)]
    return units


