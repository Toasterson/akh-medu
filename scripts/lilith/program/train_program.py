@dataclasses.dataclass(frozen=True)
class Approval:
    run_id: str
    manifest_sha256: str
    main_sha: str
    operator: str
    approved_at: str
    init_adapter_sha256: str | None
    file_sha256: str


def load_approval(path: Path, manifest: ProgramManifest, main_sha: str, init_sha: str | None) -> Approval:
    """Same guard style as history/train.py: the go must bind exactly this manifest and main."""
    path = Path(path)
    _require(path.is_file(), 'approval_missing', f'{path} is missing', 'the operator must approve this exact manifest')
    consent = read_json(path)
    _require(isinstance(consent, dict) and consent.get('decision') == 'go', 'approval_decision',
             'explicit operator go for this program is absent', 'record decision "go" bound to the manifest sha256')
    _require(consent.get('run_id') == manifest.run_id, 'approval_run', 'operator go names another run_id', 'issue a go for this run')
    _require(consent.get('manifest_sha256') == manifest.sha256, 'approval_manifest',
             'operator go does not bind the exact program manifest',
             f'the manifest sha256 is {manifest.sha256}; any change to the manifest needs a new go')
    _require(consent.get('main_sha') == main_sha, 'approval_main', 'operator go does not bind the exact main source commit',
             'build the payload from the approved origin/main commit')
    _require(bool(consent.get('operator')) and bool(consent.get('approved_at')), 'approval_attribution',
             'operator approval attribution/time missing', 'record operator and approved_at')
    datetime.datetime.fromisoformat(str(consent['approved_at']).replace('Z', '+00:00'))
    bound = consent.get('init_adapter_sha256')
    _require(bound == init_sha, 'approval_init_adapter',
             f'operator go binds init adapter {bound!r} but this launch uses {init_sha!r}',
             'the starting adapter is part of the approved recipe; approve it or start from the parent')
    return Approval(manifest.run_id, manifest.sha256, main_sha, consent['operator'], consent['approved_at'], bound,
                    sha256_file(path))


# -------------------------------------------------------------------- init adapter

def check_init_adapter(directory: Path, expected_sha256: str, config: trainer.TrainerConfig) -> dict[str, Any]:
    """Validate a starting adapter (pilot candidate) against the trainer surface; record the decision."""
    directory = Path(directory)
    weights, cfg_path = directory / 'adapter_model.safetensors', directory / 'adapter_config.json'
    _require(weights.is_file() and cfg_path.is_file(), 'init_adapter_files',
             f'{directory} lacks adapter_model.safetensors or adapter_config.json',
             'point --init-adapter at a PEFT adapter directory, or start from the parent')
    _require(_SHA256.match(expected_sha256 or '') is not None, 'init_adapter_pin', 'init adapter needs its expected sha256',
             'pass --init-adapter-sha256 (the adapter_model.safetensors sha256)')
    observed = sha256_file(weights)
    _require(observed == expected_sha256, 'init_adapter_hash',
             f'init adapter sha256 {observed} != expected {expected_sha256}', 'never train from an unpinned adapter')
    cfg = read_json(cfg_path)
    problems = []
    if cfg.get('peft_type') != 'LORA':
        problems.append(f'peft_type {cfg.get("peft_type")!r} is not LORA')
    if cfg.get('r') != config.rank:
        problems.append(f'rank {cfg.get("r")} != trainer rank {config.rank}')
    if cfg.get('lora_alpha') != config.lora_alpha:
        problems.append(f'alpha {cfg.get("lora_alpha")} != trainer alpha {config.lora_alpha}')
    if cfg.get('target_modules') != trainer.LANGUAGE_MODEL_TARGETS:
        problems.append('target_modules differ from the declared language-model surface')
    if cfg.get('bias') not in (None, 'none') or cfg.get('use_dora') or cfg.get('rank_pattern') or cfg.get('alpha_pattern'):
        problems.append('bias/DoRA/rank_pattern/alpha_pattern differ from the plain LoRA surface')
    if problems:
        raise ProgramError('lilith::program::init_adapter_incompatible', '; '.join(problems),
                           f'options: (1) launch with --rank {cfg.get("r")} if that rank is declared; '
                           '(2) start from the frozen parent without --init-adapter; (3) retrain the adapter on this surface')
    receipt_path = directory / 'lilith-adapter-receipt.json'
    tensor_sha = read_json(receipt_path).get('tensor_sha256') if receipt_path.is_file() else None
    return {'directory': str(directory), 'adapter_model_sha256': observed, 'tensor_sha256': tensor_sha,
            'rank': cfg['r'], 'lora_alpha': cfg['lora_alpha'], 'decision': 'adopted_as_starting_point',
            'checked': ['sha256', 'peft_type', 'rank', 'alpha', 'target_modules', 'plain_lora']}


